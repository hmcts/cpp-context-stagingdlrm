#!/usr/bin/env python3
"""Build the LIBRA schema-impact matrix: one CSV row per payload field, across every schema it
has to pass through, plus the change each schema needs.

    libra_field, jsonpath, container,
    funcapp_xhibit_status, funcapp_libra_action, canonical_field, canonical_status,
    pcfdlrm_field, pcfdlrm_status, progression_field, progression_status,
    change_required, change_type, change_detail, tier, notes

The four schema tiers a migrated case crosses, in order:

    FUNC-APP    stagingdlrm-azure-functions/src/main/resources — the gate that validates case.json
                before anything is enqueued. Shallow: it constrains caseDetails and the manifest
                only, and its objects are mostly OPEN, so it rejects on missing `required` fields
                rather than on unknown ones.
                Two columns, because the func-app is gaining a SECOND schema rather than changing
                its one: `funcapp_xhibit_status` is what the existing hardwired XHIBIT schema
                enforces today (it stays exactly as it is), and `funcapp_libra_action` is what the
                new source-system-selected LIBRA schema should do with the field. The XHIBIT column
                is the baseline you author the LIBRA one against — its `required` entries are
                precisely what a copy-paste of the XHIBIT file would wrongly demand of LIBRA.
    CANONICAL   stagingdlrm-domain-value-schema — what the command API actually enforces. Deep and
                CLOSED (additionalProperties:false), so a novel LIBRA field must be added here
                explicitly or the submission is rejected as a terminal, non-retryable 4xx.
    PCFDLRM     cpp-context-prosecution-casefile-dlrm — the downstream consumer. A field the
                canonical schema accepts but PCFDLRM does not model is write-only.
    PROGRESSION reached through the shared core case model (cpp.platform.core.domain
                criminal-court-public-model, rooted at apiProsecutionCase.json). A core field that
                is not reachable from that root is not part of the model a migrated case travels.

XHIBIT has no column: it is already in production, so every field the canonical schema carries
today demonstrably flows end to end. Those rows read `already_flowing` on the downstream columns,
and the interesting rows are the ones where LIBRA and the canonical schema disagree.

Joined on JSONPath (not on definition name), so structurally-equivalent fields line up even where
the schemas organise their `definitions` differently. Rooted at `$.migratedCase`: the
submission-envelope fields the Function App assembles from manifest.json / the blob path
(`submissionId`, `metadata`, `materials`, `channel`, `azureLocation`) are out of scope.

Inputs — generated by the sibling scripts, or read straight from the repos:
    schema/libra/dlrm-libra-0.13.json                       <- generate-dlrm-schema.py
    schema/canonical/staging-dlrm-canonical-flattened.json  <- flatten-canonical-schema.py
    schema/canonical/staging-dlrm-funcapp-flattened.json    <- flatten-canonical-schema.py
    ~/work/repo/cpp-context-prosecution-casefile-dlrm       <- --pcfdlrm
    ~/work/repo/cpp-context-progression                     <- --progression
    ~/work/repo/cpp.platform.core.domain                    <- --core

The PCFDLRM/core mapping for the LIBRA-added fields is hand-curated in MAPPING below — deciding
that LIBRA's `licenseCode` is PCFDLRM's `driverLicenceCode` is a judgement, not something a name
match can establish. Every curated claim is VERIFIED against the checkouts on each run, so the
table cannot silently rot: if a claimed field stops existing, this script fails loudly. Reads
sibling repo checkouts, never Maven artefacts; degrades to unverified output with a warning if a
repo is missing.

Usage:
    python3 tools/schema-gen/build-schema-impact.py                 # markdown table to stdout
    python3 tools/schema-gen/build-schema-impact.py --format csv    # CSV to stdout
    python3 tools/schema-gen/build-schema-impact.py --out           # CSV to the default path,
                                                                    # UTF-8 BOM for Excel
    # just the work list:
    python3 tools/schema-gen/build-schema-impact.py --changes-only --format csv

No cell is left blank except `notes`: a column that does not apply to a row says so explicitly
(`n/a`, or `n/a-already-in-canonical` for `tier`) rather than being empty, so a deliberate answer
cannot be misread as missing data. See NA_FILLED_COLUMNS.
"""

