def canonical_status(canon, libra):
    if libra is None:
        return CANON_ABSENT_LIBRA
    same = canon["constraints"] == libra["constraints"]
    if same and canon["required"] == libra["required"]:
        return CANON_SAME
    if same and canon["required"] and not libra["required"]:
        return CANON_REQ_CANONICAL
    if same and libra["required"] and not canon["required"]:
        return CANON_REQ_LIBRA
    return CANON_CONSTRAINT


def funcapp_xhibit_status(path, func_leaves, func_objects):
    """What the live, hardwired XHIBIT gate schema enforces at this path today."""
    entry = func_leaves.get(path)
    if entry is not None:
        return FUNC_REQUIRED if entry["required"] else FUNC_OPTIONAL
    # Not declared. Whether that matters depends on the enclosing object: the func-app's
    # caseDetails and migratedCase are OPEN, so unknown fields sail through; its
    # migrationSourceSystem and submission root are closed, so they would be rejected.
    parent = path.rpartition(".")[0]
    holder = func_objects.get(parent)
    if holder is None:
        return FUNC_NOT_VALIDATED
    return FUNC_REJECTED if holder["closed"] else FUNC_NOT_VALIDATED


def funcapp_libra_action(path, libra, gate_depth):
    """What the new source-system-selected LIBRA gate schema should do with this field.

    Read off the generated LIBRA schema, so it reflects the workbook and not an assumption about
    the design. XHIBIT's own gate schema is never consulted here — it is not changing.
    """
    if not path.startswith(GATE_DEPTHS[gate_depth]):
        return GATE_OUT_OF_SCOPE
    if libra is None:
        return GATE_OMIT
    return GATE_REQUIRE if libra["required"] else GATE_DECLARE


def libra_constraints(libra):
    """LIBRA's constraints with the known generator artefact removed.

    The generator adds `minimum: 0` to every N<n> integer because the sheet's format code implies
    unsigned; the canonical schema simply omits it. Left in, it reads as "LIBRA allows 0 where
    canonical starts at 1" and invents a relaxation nobody asked for.
    """
    return {k: v for k, v in libra["constraints"].items() if not (k == "minimum" and v == 0)}


def is_generator_artefact(canon, libra):
    return libra_constraints(libra) == canon["constraints"]


def relaxation_needed(canon, libra):
    """Does the CANONICAL constraint have to be widened for LIBRA's values to pass?

    Returns (change_type, human description). Direction matters: an absent bound is an UNBOUNDED
    one, so `maxLength 100` on the LIBRA side against no maxLength in canonical means canonical is
    already the more permissive of the two and needs no change. A LIBRA bound that is the same or
    tighter is likewise not a schema change — that rule simply belongs in the LIBRA validation
    rules. Only where canonical is demonstrably the narrower side is a relaxation real; where the
    sheet is silent about a bound canonical enforces, no rule here can adjudicate it, so it is
    handed back for review rather than guessed at.
    """
    c, l = canon["constraints"], libra_constraints(libra)

    canon_enum, libra_enum = c.get("enum"), l.get("enum")
    if canon_enum and (not libra_enum or set(libra_enum) - set(canon_enum)):
        allowed = "/".join(map(str, canon_enum))
        if libra_enum:
            supplies = "/".join(map(str, libra_enum))
        elif libra.get("values"):
            supplies = libra["values"]
        else:
            supplies = "other codes documented in the sheet"
        return CH_RELAX_ENUM, (f"drop or extend the enum {allowed} — LIBRA supplies {supplies}")

    if c.get("type") != l.get("type") and c.get("type") and l.get("type"):
        return CH_REVIEW_CONSTRAINT, f"type differs — LIBRA {l['type']} vs canonical {c['type']}"

    if c.get("$ref") != l.get("$ref") and (c.get("$ref") or l.get("$ref")):
        return CH_REVIEW_CONSTRAINT, (f"$ref differs — LIBRA {l.get('$ref') or 'inline'} vs "
                                      f"canonical {c.get('$ref') or 'inline'}")

    wider, unbounded = [], []
    for key, libra_is_wider in (("maxLength", True), ("maximum", True), ("minItems", True),
                                ("minLength", False), ("minimum", False)):
        if key not in c:
            continue                      # canonical is unbounded here — already the wider side
        if key not in l:
            unbounded.append(f"{key} {c[key]}")
        elif (l[key] > c[key]) if libra_is_wider else (l[key] < c[key]):
            wider.append(f"{key} to {l[key]} (canonical {c[key]})")
    if wider:
        return CH_RELAX_CONSTRAINT, "widen " + "; ".join(wider)

    if unbounded:
        return CH_REVIEW_CONSTRAINT, ("canonical bounds " + "; ".join(unbounded)
                                      + " where the sheet states no limit — confirm LIBRA values "
                                        "fit before deciding")

    if c.get("pattern") and not l.get("pattern"):
        return CH_REVIEW_CONSTRAINT, ("canonical enforces a pattern the sheet does not describe — "
                                      "confirm LIBRA values match it")

    return CH_LIBRA_RULE, ("Canonical already permits LIBRA's values; the sheet's tighter rule "
                           "belongs in the LIBRA validation rules")


def container_of(path):
    """Readable owner of a leaf: the jsonpath parent with the `$.migratedCase.` root stripped."""
    parent = path.rpartition(".")[0]
    return parent.replace("$.migratedCase", "").lstrip(".") or "migratedCase"


def funcapp_clause(xhibit_status, action, name):
    """The func-app sentence in change_detail.

    Always phrased as work on the NEW LIBRA schema. The existing XHIBIT schema is never modified —
    the gate gains a source-system-selected second schema — so this never says "relax".
    """
    if action == GATE_OUT_OF_SCOPE:
        return "Func-app: below the gate's validation depth — no change"
    if action == GATE_OMIT:
        if xhibit_status in (FUNC_REQUIRED, FUNC_OPTIONAL):
            return (f"Func-app: the XHIBIT gate schema declares {name} "
                    f"({xhibit_status}) — the new LIBRA schema must OMIT it, so do not carry the "
                    "entry across when authoring that file; XHIBIT's own file is unchanged")
        return f"Func-app: nothing to do — LIBRA does not supply {name}"
    if action == GATE_REQUIRE:
        return (f"Func-app: declare and require {name} in the new LIBRA schema — the sheet marks "
                "it mandatory for every LIBRA case type; XHIBIT's own file is unchanged")
    return (f"Func-app: declare {name} as optional in the new LIBRA schema — the generated "
            "caseDetails is closed (additionalProperties:false), so an undeclared field is "
            "rejected at the gate; XHIBIT's own file is unchanged")


