def decide(path, canon, libra, renamed_to, status, xhibit_status, gate_action, mapping,
           parent_closed=False):
    name = canon["name"] if canon else libra["name"]
    container = container_of(path)
    func = funcapp_clause(xhibit_status, gate_action, name)

    # --- a field LIBRA introduces -------------------------------------------------------
    if canon is None:
        tier, pcf_field, _pcf_file, _core_field, _core_file, recommendation = mapping
        if tier == T5:
            if not parent_closed:
                return "no", CH_DEFER, f"{recommendation}. {func}"
            # "Do not add yet" is only free if the payload can carry the field harmlessly. Where
            # the canonical parent is CLOSED it cannot: an undeclared property is a terminal 4xx,
            # so deferring the downstream mapping still forces a decision at the schema.
            return "yes", CH_DECLARE_ONLY, (
                f"Canonical: nothing downstream models {name}, but {container} is closed "
                "(additionalProperties:false), so a LIBRA payload carrying it is rejected outright. "
                "Either declare it as an accepted-but-unmapped optional field, or strip it before "
                f"the command call — do NOT map it onward. {recommendation}. {func}")
        change = CH_ADD_FIELD if tier in (T1, T2) else CH_ADD_BLOCKED
        detail = f"Canonical: add {name} to {container} as optional (the object is closed, so an " \
                 f"undeclared field is a terminal 4xx). {recommendation}"
        if tier in (T3, T4):
            gap = "PCFDLRM has no home for it yet, so canonical alone makes it write-only"
            detail = f"{detail}. PCFDLRM: {gap}"
        if gate_action in (GATE_REQUIRE, GATE_DECLARE) or xhibit_status == FUNC_REQUIRED:
            detail = f"{detail}. {func}"
        return "yes", change, detail

    # --- LIBRA supplies the same concept under another name -----------------------------
    if renamed_to:
        return "yes", CH_MAP_RENAME, (
            f"Transformation: LIBRA supplies {renamed_to} (a reference-data code) where canonical "
            f"{container}.{name} expects a resolved UUID — resolve it in the LIBRA transformation "
            f"strategy, not by loosening the canonical type. {func}")

    # --- LIBRA does not supply the field at all -----------------------------------------
    if libra is None:
        if canon.get("alternatives"):
            return "yes", CH_RELAX_COMBINATOR, (
                f"Canonical: {container} requires one of {name}/{'/'.join(canon['alternatives'])} "
                f"via an anyOf branch, and the LIBRA sheet has none of them — drop or "
                f"source-system-scope that branch. {GUARD}. {func}")
        if canon["required"]:
            return "yes", CH_RELAX_REQUIRED, (
                f"Canonical: make {container}.{name} optional — LIBRA never supplies it. "
                f"{GUARD}. {func}")
        return "no", CH_NONE, f"LIBRA does not supply it and canonical already allows that. {func}"

    # --- present on both sides ----------------------------------------------------------
    if status == CANON_REQ_LIBRA:
        return "no", CH_LIBRA_RULE, (
            f"Canonical already permits it; the sheet's mandatory mark for {name} must be "
            f"enforced in the LIBRA validation rules, not the shared schema. {func}")

    if status == CANON_REQ_CANONICAL:
        return "yes", CH_RELAX_REQUIRED, (
            f"Canonical: make {container}.{name} optional — the sheet marks it optional or "
            f"conditionally mandatory for at least one LIBRA case type. {GUARD}. {func}")

    if status == CANON_CONSTRAINT:
        if is_generator_artefact(canon, libra):
            return "no", CH_NONE, ("Generator artefact only (minimum:0 added for N-format "
                                   f"integers) — not a real difference. {func}")
        change, why = relaxation_needed(canon, libra)
        if change == CH_LIBRA_RULE:
            return "no", change, f"{why}. {func}"
        if change == CH_REVIEW_CONSTRAINT:
            return "yes", change, (f"Canonical: {container}.{name} — {why}. If it is relaxed, "
                                   f"guard: {GUARD_TAIL}. {func}")
        return "yes", change, f"Canonical: {why} on {container}.{name}. {GUARD}. {func}"

    return "no", CH_NONE, f"Identical on both sides. {func}"


