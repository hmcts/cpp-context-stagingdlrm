def note_text(canon, libra, status, mapping):
    notes = []
    if canon is None:
        if libra and libra["row"]:
            notes.append(f"LIBRA sheet row {libra['row']}")
        if mapping:
            notes.append(mapping[5])
    else:
        if status == CANON_CONSTRAINT and libra:
            notes.append(f"LIBRA {render(libra['constraints'])} vs canonical "
                         f"{render(canon['constraints'])}")
        if canon["required"] and libra is None:
            notes.append("**required in canonical but absent from the LIBRA sheet — blocker**")
        if canon.get("alternatives"):
            notes.append("part of an anyOf required-branch with "
                         + "/".join(canon["alternatives"]))
    return "; ".join(notes)


def render(constraints):
    if not constraints:
        return "—"
    bits = []
    for key, value in constraints.items():
        if key == "pattern":
            bits.append("pattern")
        elif key == "enum":
            bits.append("enum " + "/".join(map(str, value)))
        elif key == "type":
            bits.append(str(value))
        else:
            bits.append(f"{key} {value}")
    return ", ".join(bits)


def build(libra_path=None, canonical_path=None, funcapp_path=None,
          gate_depth=DEFAULT_GATE_DEPTH):
    libra_doc = json.loads(Path(libra_path or DEFAULT_LIBRA).read_text(encoding="utf-8"))
    canon_doc = json.loads(Path(canonical_path or DEFAULT_CANONICAL).read_text(encoding="utf-8"))
    func_path = Path(funcapp_path or DEFAULT_FUNCAPP)
    if not func_path.exists():
        sys.exit(f"error: {func_path} not found — run flatten-canonical-schema.py against "
                 "stagingdlrm-azure-functions/src/main/resources first (regenerate.sh does)")
    func_doc = json.loads(func_path.read_text(encoding="utf-8"))

    L, _ = walk(libra_doc, ROOT_PROPERTY)
    C, C_objects = walk(canon_doc, ROOT_PROPERTY)
    F, F_objects = walk(func_doc, ROOT_PROPERTY)
    for store in (L, C, F):
        drop_envelope(store)

    verified = PCF_SCHEMA.is_dir()
    if not verified:
        print(f"warning: {PCFDLRM} not found — PCFDLRM claims are UNVERIFIED", file=sys.stderr)
    closure, modules = core_closure()
    if closure is None:
        print(f"warning: {CORE} not found or {PROGRESSION_ROOT} missing — Progression claims are "
              "UNVERIFIED", file=sys.stderr)
    else:
        print(f"payload closure from {PROGRESSION_ROOT}: {len(closure)} schemas, modules={modules}",
              file=sys.stderr)

    rows, matched, failures = [], set(), []

    # --- every canonical field, LIBRA measured against it -------------------------------
    for path, canon in C.items():
        parent, _, name = path.rpartition(".")
        renamed_to = RENAMES.get((parent, name))
        l_path = f"{parent}.{renamed_to}" if renamed_to else path
        libra = L.get(l_path)
        if libra is not None:
            matched.add(l_path)

        status = CANON_RENAMED if (renamed_to and libra) else canonical_status(canon, libra)
        xhibit_status = funcapp_xhibit_status(path, F, F_objects)
        gate_action = funcapp_libra_action(path, libra, gate_depth)
        required, change_type, change_detail = decide(
            path, canon, libra, renamed_to if libra else None, status, xhibit_status, gate_action,
            None)
        rows.append({
            "libra_field": libra["name"] if libra else "",
            "jsonpath": path,
            "container": container_of(path),
            "funcapp_xhibit_status": xhibit_status,
            "funcapp_libra_action": gate_action,
            "canonical_field": name,
            "canonical_status": status,
            # Already in the canonical schema and exercised by XHIBIT in production, so both
            # downstream hops are taken as given. The LIBRA-driven risk on these rows is the
            # RELAXATION, which change_type carries (relax-* => an XHIBIT rule is now needed,
            # libra-rule-only => a LIBRA rule is).
            "pcfdlrm_field": "",
            "pcfdlrm_status": DOWN_FLOWING,
            "progression_field": "",
            "progression_status": PROG_ASSUMED,
            "change_required": required,
            "change_type": change_type,
            "change_detail": change_detail,
            "tier": "",
            "notes": note_text(canon, libra, status, None),
        })

    # --- fields LIBRA adds --------------------------------------------------------------
    added = [(p, e) for p, e in L.items() if p not in matched and p not in C]
    unmapped = sorted({e["name"] for _p, e in added if e["name"] not in MAPPING})
    if unmapped:
        sys.exit(f"error: no curated mapping for {unmapped} — update MAPPING")
    stale = sorted(set(MAPPING) - {e["name"] for _p, e in added})
    if stale:
        print(f"warning: MAPPING has entries no longer in the LIBRA schema: {stale}",
              file=sys.stderr)

    for path, libra in added:
        mapping = MAPPING[libra["name"]]
        xhibit_status = funcapp_xhibit_status(path, F, F_objects)
        gate_action = funcapp_libra_action(path, libra, gate_depth)
        pcf_field, pcf_status, prog_field, prog_status = downstream(
            libra["name"], mapping, verified, closure, failures, container_of(path))
        parent_closed = (C_objects.get(path.rpartition(".")[0]) or {}).get("closed", False)
        required, change_type, change_detail = decide(
            path, None, libra, None, CANON_ADDED, xhibit_status, gate_action, mapping,
            parent_closed)
        rows.append({
            "libra_field": libra["name"],
            "jsonpath": path,
            "container": container_of(path),
            "funcapp_xhibit_status": xhibit_status,
            "funcapp_libra_action": gate_action,
            "canonical_field": "",
            "canonical_status": CANON_ADDED,
            "pcfdlrm_field": pcf_field,
            "pcfdlrm_status": pcf_status,
            "progression_field": prog_field,
            "progression_status": prog_status,
            "change_required": required,
            "change_type": change_type,
            "change_detail": change_detail,
            "tier": mapping[0],
            "notes": note_text(None, libra, CANON_ADDED, mapping),
        })

    if failures:
        sys.exit("error: curated downstream claims no longer hold:\n  " + "\n  ".join(failures))

    # Work first, then by tier, then by depth — so the rows that need doing sort to the top.
    rows.sort(key=lambda r: (r["change_required"] != "yes", TIER_ORDER[r["tier"]],
                             r["jsonpath"].count("."), r["jsonpath"]))
    return fill_na(rows)


def fill_na(rows):
    """Replace structurally-empty cells with an explicit marker. Applied after sorting."""
    for row in rows:
        for col in NA_FILLED_COLUMNS:
            if not row[col]:
                row[col] = NA
        if not row["tier"]:
            row["tier"] = TIER_NA
    return rows


def plain(text):
    """Strip markdown emphasis — CSV readers show it literally.

    Applied ONLY to prose columns: a blanket strip would also eat the `*` in `defendants[*]`,
    silently corrupting every array jsonpath.
    """
    return re.sub(r"\*\*|`", "", str(text))


def main():
    global PCFDLRM, CORE, PCF_SCHEMA

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--format", choices=("markdown", "csv"), default="markdown")
    ap.add_argument("--libra", help="generated LIBRA schema (default: the committed one)")
    ap.add_argument("--canonical", help="flattened canonical schema (default: the committed one)")
    ap.add_argument("--funcapp", help="flattened func-app schema (default: the committed one)")
    ap.add_argument("--pcfdlrm", default=str(PCFDLRM),
                    help="cpp-context-prosecution-casefile-dlrm checkout")
    ap.add_argument("--core", default=str(CORE), help="cpp.platform.core.domain checkout")
    ap.add_argument("--funcapp-libra-depth", choices=sorted(GATE_DEPTHS),
                    default=DEFAULT_GATE_DEPTH,
                    help="how deep the new LIBRA gate schema is assumed to validate, which decides "
                         "funcapp_libra_action. 'case-details' (default) mirrors the depth the "
                         "XHIBIT gate uses today; 'full' assumes the generated LIBRA schema is used "
                         "at its own depth")
    ap.add_argument("--changes-only", action="store_true",
                    help="emit only the rows where change_required is yes")
    ap.add_argument("--out-dir", default=".",
                    help="directory to write the CSV into (default: current directory)")
    ap.add_argument("--out", nargs="?", const="",
                    help="write CSV instead of stdout; bare --out uses --out-dir, "
                         "or give an explicit path")
    args = ap.parse_args()

    PCFDLRM = Path(args.pcfdlrm)
    CORE = Path(args.core)
    PCF_SCHEMA = PCFDLRM / "pcfdlrm-domain/pcfdlrm-domain-value-schema/src/main/resources/json/schema"

    rows = build(args.libra, args.canonical, args.funcapp, args.funcapp_libra_depth)
    total = len(rows)
    if args.changes_only:
        rows = [r for r in rows if r["change_required"] == "yes"]

    if args.format == "csv" or args.out is not None:
        # utf-8-sig: Excel needs the BOM to read the em dashes as UTF-8 rather than mojibake.
        # Values are also guarded against being read as formulas.
        clean = []
        for r in rows:
            row = {c: (plain(r[c]) if c in MARKDOWN_COLUMNS else str(r[c])) for c in COLUMNS}
            for c, v in row.items():
                if v[:1] in ("=", "+", "-", "@"):
                    row[c] = "'" + v
            clean.append(row)
        if args.out is not None:
            out = Path(args.out) if args.out else Path(args.out_dir) / DEFAULT_NAME
            out.parent.mkdir(parents=True, exist_ok=True)
            with out.open("w", encoding="utf-8-sig", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=COLUMNS)
                w.writeheader()
                w.writerows(clean)
            print(f"WROTE: {out}   {len(clean)} rows x {len(COLUMNS)} columns")
        else:
            w = csv.DictWriter(sys.stdout, fieldnames=COLUMNS)
            w.writeheader()
            w.writerows(clean)
    else:
        print("| " + " | ".join(COLUMNS) + " |")
        print("|" + "|".join(["---"] * len(COLUMNS)) + "|")
        code_columns = ("libra_field", "jsonpath", "container", "canonical_field", "pcfdlrm_field")
        for r in rows:
            cells = [str(r[c]).replace("|", "\\|") for c in COLUMNS]
            cells = [f"`{c}`" if col in code_columns and c and c != NA else c
                     for col, c in zip(COLUMNS, cells)]
            print("| " + " | ".join(cells) + " |")

    tally = {}
    for r in rows:
        for col in ("change_type", "funcapp_xhibit_status", "funcapp_libra_action",
                    "canonical_status"):
            tally.setdefault(col, {}).setdefault(r[col], 0)
            tally[col][r[col]] += 1
    changes = sum(1 for r in rows if r["change_required"] == "yes")
    print(f"\n<!-- {len(rows)} of {total} rows; {changes} need a change", file=sys.stderr)
    for col, counts in tally.items():
        print(f"     {col}: {dict(sorted(counts.items()))}", file=sys.stderr)
    print("-->", file=sys.stderr)


if __name__ == "__main__":
    main()
