def schema_property_names(path):
    """Every property name declared anywhere in a JSON Schema file."""
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return set()
    names = set()

    def walk_node(node):
        if isinstance(node, dict):
            if isinstance(node.get("properties"), dict):
                names.update(node["properties"])
            for value in node.values():
                walk_node(value)
        elif isinstance(node, list):
            for value in node:
                walk_node(value)

    walk_node(doc)
    return names


def field_type(path, leaf):
    """Constraint summary for `leaf` in the given schema file."""
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return ""
    found = []

    def walk_node(node):
        if isinstance(node, dict):
            props = node.get("properties")
            if isinstance(props, dict) and leaf in props and isinstance(props[leaf], dict):
                found.append(props[leaf])
            for value in node.values():
                walk_node(value)
        elif isinstance(node, list):
            for value in node:
                walk_node(value)

    walk_node(doc)
    if not found:
        return ""
    node = found[0]
    bits = []
    for key in ("type", "$ref", "maxLength", "minLength", "maximum", "minimum"):
        if key in node:
            value = node[key]
            if key == "$ref":
                value = str(value).rsplit("/", 1)[-1].rsplit("#", 1)[0]
            bits.append(f"{key}={value}")
    return " ".join(bits)


def core_closure(root_name=PROGRESSION_ROOT):
    """{basename: (property names, required names)} for every schema reachable from the payload root.

    Indexes the WHOLE core repo (all modules, src/ only) and follows $ref by absolute id, so a
    cross-module hop resolves rather than silently truncating the closure. Today the closure is
    entirely within criminal-court-public-model; the module tally is reported so that changing
    becomes visible instead of invisible.

    A field existing somewhere in core is not enough — core also holds outcome, enforcement, SJP
    and design schemas a migrated case never touches. Only what hangs off the payload root counts.
    """
    if not CORE.is_dir():
        return None, {}
    by_path, by_id = {}, {}
    for path in CORE.rglob("*.json"):
        sp = str(path)
        if "/target/" in sp or "/src/" not in sp:
            continue
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        real = os.path.realpath(path)
        by_path[real] = doc
        schema_id = doc.get("id") or doc.get("$id")
        if schema_id:
            by_id.setdefault(schema_id, real)

    def refs_of(doc):
        out = []

        def walk_node(node):
            if isinstance(node, dict):
                if isinstance(node.get("$ref"), str):
                    out.append(node["$ref"])
                for value in node.values():
                    walk_node(value)
            elif isinstance(node, list):
                for value in node:
                    walk_node(value)

        walk_node(doc)
        return out

    root = next((p for p in by_path
                 if os.path.basename(p) == root_name and "criminal-court-public-model" in p), None)
    if root is None:
        return None, {}
    seen, queue = {root}, [root]
    while queue:
        cur = queue.pop()
        for ref in refs_of(by_path.get(cur) or {}):
            base = ref.split("#")[0]
            if not base:
                continue
            nxt = by_id.get(base) if base.startswith("http") else os.path.realpath(
                os.path.join(os.path.dirname(cur), base))
            if nxt and nxt in by_path and nxt not in seen:
                seen.add(nxt)
                queue.append(nxt)

    closure = {}
    for real in seen:
        acc = []

        def walk_node(node):
            if isinstance(node, dict):
                if isinstance(node.get("properties"), dict):
                    acc.append((set(node["properties"]), set(node.get("required", []))))
                for value in node.values():
                    walk_node(value)
            elif isinstance(node, list):
                for value in node:
                    walk_node(value)

        walk_node(by_path[real])
        if acc:
            closure[os.path.basename(real)] = (set().union(*[a[0] for a in acc]),
                                              set().union(*[a[1] for a in acc]))
    modules = {}
    for real in seen:
        try:
            mod = str(Path(real).relative_to(CORE)).split("/")[0]
        except ValueError:
            mod = "?"
        modules[mod] = modules.get(mod, 0) + 1
    return closure, modules


def progression_status(closure, core_field, core_file, fallback_names=(), scope_file=None):
    """(status, where) for one field against the payload closure.

    A curated (core_field, core_file) claim always wins over a name search: a bare name match picks
    an arbitrary schema, which is how `forename`/`surname` once resolved to judicialRole.json and
    came out mandatory for entirely the wrong reason.
    """
    if closure is None:
        return DOWN_UNVERIFIED, f"{core_file}#{core_field}" if core_field else ""
    if core_field and core_file:
        entry = closure.get(core_file)
        if entry and core_field in entry[0]:
            status = PROG_MANDATORY if core_field in entry[1] else PROG_OPTIONAL
            return status, f"{core_file}#{core_field}"
        return PROG_NONE, ""
    for name in fallback_names:
        if not name:
            continue
        if scope_file:
            entry = closure.get(scope_file)
            if entry and name in entry[0]:
                status = PROG_MANDATORY if name in entry[1] else PROG_OPTIONAL
                return status, f"{scope_file}#{name} (name match)"
            continue
        for bn, (props, req) in sorted(closure.items()):
            if name in props:
                status = PROG_MANDATORY if name in req else PROG_OPTIONAL
                return status, f"{bn}#{name} (unscoped name match)"
    return PROG_NONE, ""


def downstream(field, mapping, verified, closure, failures, container=None):
    """(pcfdlrm_field, pcfdlrm_status, progression_field, progression_status) for a LIBRA-added
    field, verifying every curated claim against the checkouts as it goes."""
    _tier, pcf_field, pcf_file, core_field, core_file, _rec = mapping

    if not pcf_field:
        pcf_status = DOWN_MISSING
    elif not verified:
        pcf_status = DOWN_UNVERIFIED
    else:
        leaf = pcf_field.split(".")[-1]
        path = PCF_SCHEMA / pcf_file
        if not path.exists() or leaf not in schema_property_names(path):
            failures.append(f"PCFDLRM: {field} -> {pcf_file}#{leaf}")
            pcf_status = DOWN_UNVERIFIED
        else:
            pcf_status = DOWN_EXISTS if leaf == field else DOWN_RENAMED
            constraints = field_type(path, leaf)
            pcf_field = f"{pcf_file}#{pcf_field}" + (f" ({constraints})" if constraints else "")

    prog_st, prog_where = progression_status(
        closure, core_field, core_file,
        fallback_names=(field, (pcf_field or "").split("#")[-1]),
        scope_file=CONTAINER_CORE.get(container))
    if core_field and core_file and prog_st == PROG_NONE:
        failures.append(f"core: {field} -> {core_file}#{core_field} "
                        "(not in the courtReferral payload closure)")
    return pcf_field or "", pcf_status, prog_where, prog_st


