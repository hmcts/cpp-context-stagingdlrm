def deref(node, definitions, depth=0):
    """Follow $ref while the target is a scalar (no properties of its own)."""
    if depth > 8 or not isinstance(node, dict):
        return node
    ref = node.get("$ref")
    if not isinstance(ref, str) or not ref.startswith("#/definitions/"):
        return node
    leaf = ref.split("/")[-1]
    if leaf in OPAQUE_REFS:
        return {"$ref": leaf}
    target = definitions.get(leaf)
    if not isinstance(target, dict) or target.get("properties"):
        return node
    merged = {k: v for k, v in target.items() if k != "description"}
    merged.update({k: v for k, v in node.items() if k not in ("$ref", "description")})
    return deref(merged, definitions, depth + 1)


def object_target(node, definitions):
    """Return (object schema, is_array) if this node leads to an object, else (None, False)."""
    if not isinstance(node, dict):
        return None, False
    is_array = node.get("type") == "array"
    inner = node.get("items", {}) if is_array else node
    if isinstance(inner, dict) and isinstance(inner.get("$ref"), str):
        name = inner["$ref"].split("/")[-1]
        target = definitions.get(name, {})
        if isinstance(target, dict) and (target.get("properties")
                                        or any(k in target for k in ("oneOf", "anyOf"))):
            return target, is_array
        return None, is_array
    if isinstance(inner, dict) and (inner.get("properties")
                                    or any(k in inner for k in ("oneOf", "anyOf"))):
        return inner, is_array
    return None, is_array


def branches(obj):
    """An object plus any oneOf/anyOf branches, so union-typed nodes contribute all their fields."""
    out = [obj]
    for key in ("oneOf", "anyOf"):
        for branch in obj.get(key, []) or []:
            if isinstance(branch, dict):
                out.append(branch)
    return out


def combinator_required(obj):
    """Names demanded by a pure `{"required": [...]}` anyOf/oneOf branch.

    The canonical caseDetails carries `anyOf: [{required:[dateOfCommittal]},
    {required:[dateOfSending]}]` — a blocker that lives in neither `properties` nor the top-level
    `required`, so a matrix that only diffed those two would silently miss it. Returns
    {name: [alternatives]} so each affected leaf can name the other side of the choice.
    """
    groups = []
    for key in ("oneOf", "anyOf"):
        for branch in obj.get(key, []) or []:
            if isinstance(branch, dict) and set(branch) == {"required"}:
                groups.append(list(branch["required"]))
    out = {}
    for group in groups:
        for name in group:
            others = [n for g in groups for n in g if n != name]
            out.setdefault(name, sorted(set(others)))
    return out


def walk(schema, root_property):
    """Return (leaves, objects) keyed by jsonpath.

    leaves[path]  = {name, constraints, ref, array, required, row, alternatives}
    objects[path] = {closed: bool}   — `closed` means additionalProperties:false, i.e. an unknown
                                      field here is rejected rather than ignored.
    """
    definitions = schema.get("definitions", {})
    leaves, objects = OrderedDict(), OrderedDict()

    root = schema.get("properties", {}).get(root_property)
    if root is None:                                  # canonical/func-app root via $ref
        ref = schema.get("$ref")
        entry = definitions.get(ref.split("/")[-1], {}) if isinstance(ref, str) else {}
        root = entry.get("properties", {}).get(root_property)
    if root is None:
        sys.exit(f"error: no {root_property!r} in {schema.get('id')}")

    def descend(node, path, seen):
        obj, is_array = object_target(node, definitions)
        if obj is None:
            return
        marker = f"{path}{'[*]' if is_array else ''}"
        if marker in seen:
            return
        seen = seen | {marker}
        objects[marker] = {"closed": obj.get("additionalProperties") is False}
        alternatives = combinator_required(obj)
        for holder in branches(obj):
            required = set(holder.get("required", []))
            for name, child in (holder.get("properties") or {}).items():
                child_path = f"{marker}.{name}"
                resolved = deref(child, definitions)
                sub, sub_array = object_target(child, definitions)
                if sub is not None:
                    descend(child, child_path, seen)
                    continue
                description = child.get("description", "") or ""
                row = re.search(r"Sheet row (\d+)", description)
                # The generator deliberately does NOT emit an enum for coded fields (a closed Java
                # enum downstream makes a rejection terminal), it records the codes in prose. Pull
                # them back out so a relax-enum row can name the values that have to be allowed.
                values = re.search(r"Documented values: ([^(]+)", description)
                leaves[child_path] = {
                    "name": name,
                    "constraints": {k: resolved[k] for k in CONSTRAINT_KEYS if k in resolved},
                    "ref": (child.get("$ref") or "").split("/")[-1] or None,
                    "array": sub_array or resolved.get("type") == "array",
                    "required": name in required,
                    "row": row.group(1) if row else None,
                    "values": values.group(1).strip().rstrip(".") if values else None,
                    "alternatives": alternatives.get(name),
                }

    descend({"$ref": root.get("$ref")} if root.get("$ref") else root,
            f"${'.' + root_property}", frozenset())
    return leaves, objects


def drop_envelope(store):
    for path in [p for p in store if p.split(".")[1].split("[")[0] in ENVELOPE_FIELDS]:
        del store[path]


